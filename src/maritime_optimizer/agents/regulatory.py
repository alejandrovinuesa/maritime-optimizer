"""Regulatory update agent: proposes changes to the regulatory CSVs from a new legal text.

Claude reads the new text (an amended regulation, an IMO resolution, a delegated act) next
to the current CSVs and proposes cell updates, each with the article and a verbatim quote.
The code then validates every proposal against the CSVs and the source, and writes a review
report plus a unified diff. It never modifies the CSVs: a person reviews and applies the diff.
"""

import csv
import difflib
import io
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, List, Optional

from pydantic import BaseModel

from ..paths import REGULATORY_DIR
from ._claude import FALLBACK_KWARGS, MODEL, check_refusal, make_client

# Market data, not regulation: the agent must not touch it.
EXCLUDED_FILES = {"fuel_prices.csv"}

SYSTEM = """\
You maintain the regulatory parameter tables of a maritime emissions model (EU ETS, MRV,
FuelEU Maritime, MARPOL Annex VI CII). You receive a new legal text and the current tables.

Propose a change only when the text explicitly sets or amends a value that one of the tables
stores. For each change give:
- the table file name, the columns and values that identify exactly one row, the column to change,
  the current value exactly as written in the table, and the new value in the table's units;
- the article or annex of the source, and a verbatim quote of the sentence or table row that
  sets the new value, copied character for character from the source text.
Do not propose changes that need interpretation beyond the text, unit conversions you cannot
justify from the text, or values for tables the text does not address. If nothing in the text
affects the tables, return an empty list of changes and say why.
"""


class CellMatch(BaseModel):
    column: str
    value: str


class ProposedChange(BaseModel):
    csv_file: str
    row_match: List[CellMatch]
    column: str
    current_value: str
    proposed_value: str
    article: str
    verbatim_quote: str
    rationale: str


class Proposal(BaseModel):
    summary: str
    applies_from: str
    changes: List[ProposedChange]


@dataclass
class CheckedChange:
    change: ProposedChange
    errors: List[str] = field(default_factory=list)

    @property
    def valid(self) -> bool:
        return not self.errors


@dataclass
class UpdateReview:
    source_name: str
    proposal: Proposal
    checked: List[CheckedChange]
    diff: str
    model: str = MODEL

    def to_markdown(self) -> str:
        lines = [f"# Regulatory update proposal: {self.source_name}", "",
                 f"*Generated by {self.model}. Review before applying; the CSVs were not modified.*", "",
                 f"**Summary.** {self.proposal.summary}", "",
                 f"**Applies from.** {self.proposal.applies_from}", ""]
        if not self.checked:
            lines.append("No changes proposed.")
        for i, c in enumerate(self.checked, 1):
            ch = c.change
            key = ", ".join(f"{m.column}={m.value}" for m in ch.row_match)
            lines += [f"## {i}. `{ch.csv_file}` [{key}] `{ch.column}`: "
                      f"{ch.current_value} → {ch.proposed_value}",
                      f"- Status: {'✅ passes all checks' if c.valid else '❌ rejected'}",
                      *(f"- Problem: {e}" for e in c.errors),
                      f"- Source: {ch.article}", f"- Quote: > {ch.verbatim_quote}",
                      f"- Rationale: {ch.rationale}", ""]
        if self.diff:
            lines += ["## Diff of the valid changes", "", "```diff", self.diff.rstrip(), "```"]
        return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ inputs

def read_source(path: Path) -> str:
    """Text of a .txt/.md/.html/.xml or .pdf source (PDF needs the optional 'pypdf' package)."""
    path = Path(path)
    if path.suffix.lower() == ".pdf":
        try:
            from pypdf import PdfReader
        except ImportError as exc:
            raise ImportError("Reading PDFs needs 'pypdf' (pip install pypdf), "
                              "or pass the text of the act as .txt") from exc
        return "\n".join(page.extract_text() or "" for page in PdfReader(str(path)).pages)
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() in (".html", ".htm", ".xml"):
        text = re.sub(r"<[^>]+>", " ", text)
    return text


def current_tables(reg_dir: Path = REGULATORY_DIR) -> dict:
    """{file name: CSV text} of the regulatory tables the agent may change."""
    return {p.name: p.read_text(encoding="utf-8")
            for p in sorted(Path(reg_dir).glob("*.csv")) if p.name not in EXCLUDED_FILES}


# ------------------------------------------------------------------ validation

def _norm(text: str) -> str:
    text = text.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    return re.sub(r"\s+", " ", text).strip().lower()


def _same_value(a: str, b: str) -> bool:
    try:
        return abs(float(a) - float(b)) < 1e-12
    except ValueError:
        return a.strip() == b.strip()


def check_changes(proposal: Proposal, source_text: str, tables: dict) -> List[CheckedChange]:
    """Validate each proposed change against the tables and the source text."""
    source = _norm(source_text)
    checked = []
    for ch in proposal.changes:
        c = CheckedChange(ch)
        checked.append(c)
        if ch.csv_file not in tables:
            c.errors.append(f"unknown or protected table {ch.csv_file!r}")
            continue
        rows = list(csv.DictReader(io.StringIO(tables[ch.csv_file])))
        columns = rows[0].keys() if rows else []
        missing = [m.column for m in ch.row_match if m.column not in columns]
        if ch.column not in columns:
            missing.append(ch.column)
        if missing:
            c.errors.append(f"unknown column(s) {missing}")
            continue
        hits = [r for r in rows if all(_same_value(r[m.column], m.value) for m in ch.row_match)]
        if len(hits) != 1:
            c.errors.append(f"row match selects {len(hits)} rows, expected exactly 1")
        elif not _same_value(hits[0][ch.column], ch.current_value):
            c.errors.append(f"current value is {hits[0][ch.column]!r}, not {ch.current_value!r}")
        if not ch.verbatim_quote.strip() or _norm(ch.verbatim_quote) not in source:
            c.errors.append("quote not found verbatim in the source text")
    return checked


def build_diff(checked: List[CheckedChange], tables: dict,
               prefix: str = "src/maritime_optimizer/data/regulatory") -> str:
    """Unified diff applying the valid changes (``git apply`` from the repository root)."""
    out = []
    for name, text in tables.items():
        changes = [c.change for c in checked if c.valid and c.change.csv_file == name]
        if not changes:
            continue
        reader = list(csv.reader(io.StringIO(text)))
        header, body = reader[0], reader[1:]
        for ch in changes:
            for row in body:
                record = dict(zip(header, row, strict=False))
                if all(_same_value(record[m.column], m.value) for m in ch.row_match):
                    row[header.index(ch.column)] = ch.proposed_value
        buf = io.StringIO()
        csv.writer(buf, lineterminator="\n").writerows([header, *body])
        before, after = text.splitlines(keepends=True), buf.getvalue().splitlines(keepends=True)
        out.extend(difflib.unified_diff(before, after,
                                        fromfile=f"a/{prefix}/{name}", tofile=f"b/{prefix}/{name}"))
    return "".join(out)


# ------------------------------------------------------------------ agent

def propose_update(source_path: Path, client: Optional[Any] = None, model: str = MODEL,
                   reg_dir: Path = REGULATORY_DIR) -> UpdateReview:
    """Ask Claude for CSV changes implied by a legal text, then validate them. Never writes CSVs."""
    source_path = Path(source_path)
    source_text = read_source(source_path)
    tables = current_tables(reg_dir)
    client = make_client(client)
    content = ("Current tables:\n" + json.dumps(tables, ensure_ascii=False, indent=1)
               + f"\n\nNew legal text ({source_path.name}):\n<source>\n{source_text}\n</source>")
    response = client.beta.messages.parse(
        model=model, max_tokens=16000, system=SYSTEM, output_format=Proposal,
        output_config={"effort": "high"},
        messages=[{"role": "user", "content": content}], **FALLBACK_KWARGS)
    check_refusal(response)
    proposal: Proposal = response.parsed_output
    checked = check_changes(proposal, source_text, tables)
    return UpdateReview(source_path.name, proposal, checked, build_diff(checked, tables),
                        getattr(response, "model", model))
